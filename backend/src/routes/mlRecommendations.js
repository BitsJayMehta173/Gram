import { Router } from "express";
import { execFile } from "child_process";
import { promisify } from "util";
import path from "path";
import { fileURLToPath } from "url";
import { SOIL_TYPES, WATER_SOURCES, ZONES } from "./recommendations.js";
import { SQM_PER_ACRE } from "../services/scoring.js";
import { currentSeason, SEASONS } from "../services/season.js";

const execFileAsync = promisify(execFile);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ML_DIR = path.join(__dirname, "../../../ml");
const PYTHON_BIN = path.join(ML_DIR, ".venv", "Scripts", "python.exe");
const INFER_SCRIPT = path.join(ML_DIR, "infer.py");

// Separate, additive endpoint alongside /api/recommendations -- NOT a
// replacement. Every one of these models was distilled from the same rule
// engine that powers the existing endpoint (see ml/train_*.py docstrings),
// so today the rule engine is at least as accurate as its own distillation.
// This endpoint exists to exercise the ML path end-to-end, not to supersede
// the rule-based one.
const ML_DISCLAIMER =
  "These predictions come from Random Forest models trained on backend/data/training/land_recommendation_dataset.csv, " +
  "itself generated by sweeping the same rule engine behind /api/recommendations -- not independent real-world " +
  "outcomes. Eligibility is computed with the exact rule engine (not an ML approximation); only the profit estimate " +
  "and ranking score are ML-predicted. See ml/infer.py for details.";

const router = Router();

router.post("/ml-recommendations", async (req, res) => {
  const { areaSqm, soilType, waterSource, season, budget, zone } = req.body ?? {};

  if (!Number.isFinite(areaSqm) || areaSqm <= 0) {
    return res.status(400).json({ error: "areaSqm must be a positive number" });
  }
  if (!SOIL_TYPES.includes(soilType)) {
    return res.status(400).json({ error: `soilType must be one of: ${SOIL_TYPES.join(", ")}` });
  }
  if (!WATER_SOURCES.includes(waterSource)) {
    return res.status(400).json({ error: `waterSource must be one of: ${WATER_SOURCES.join(", ")}` });
  }
  if (!ZONES.includes(zone)) {
    return res.status(400).json({ error: `zone must be one of: ${ZONES.join(", ")}` });
  }
  const resolvedSeason = season && SEASONS.includes(season) ? season : currentSeason();
  const resolvedBudget = budget != null && Number.isFinite(budget) && budget > 0 ? budget : null;
  const areaAcre = areaSqm / SQM_PER_ACRE;

  const args = [
    INFER_SCRIPT,
    "--area-acre",
    String(areaAcre),
    "--zone",
    zone,
    "--soil-type",
    soilType,
    "--water-source",
    waterSource,
    "--season",
    resolvedSeason,
    "--json",
  ];
  if (resolvedBudget != null) {
    args.push("--budget", String(resolvedBudget));
  }

  try {
    // execFile (not exec/shell) so zone/soilType/etc. are passed as discrete
    // argv entries -- no shell interpolation, and no quoting issues from the
    // space in this machine's venv path ("Dev Arya").
    const { stdout } = await execFileAsync(PYTHON_BIN, args, { timeout: 15000 });
    const parsed = JSON.parse(stdout);
    res.json({ ...parsed, disclaimer: ML_DISCLAIMER });
  } catch (err) {
    const detail = err.stderr?.trim() || err.message;
    console.error("ml-recommendations inference failed:", detail);
    res.status(500).json({ error: "ML inference failed", detail });
  }
});

export default router;
