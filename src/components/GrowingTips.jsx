import { useState } from "react";

const API_BASE = "http://localhost:4000";

// Short display names for the raw Ollama model tags stored in the dataset.
// Falls back to the raw tag for any model not listed here, so adding a new
// model pass to build_growing_tips.mjs never needs a matching change here.
const MODEL_LABELS = {
  "qwen2.5:7b-instruct": "Qwen2.5-7B",
  "llama3.1:8b": "Llama 3.1 8B",
  "mistral:7b": "Mistral 7B",
};
function modelLabel(model) {
  return MODEL_LABELS[model] ?? model;
}

// "low"/"very_low"-band items are real, non-fabricated data (a single
// unconfirmed model's guess is still that model's actual answer) -- this
// never deletes anything server-side, it only changes what's shown by
// default. Backend already sorts every list/bySource array probability-
// descending (see build_growing_tips.mjs), so filtering here is just a
// split at that sorted boundary, not a re-sort.
function splitByBand(items) {
  const shown = items.filter((i) => i.probabilityBand === "high" || i.probabilityBand === "medium");
  const hidden = items.filter((i) => i.probabilityBand === "low" || i.probabilityBand === "very_low");
  return { shown, hidden };
}

function ListEntryRow({ c }) {
  return (
    <li>
      {c.name} — {c.detail}{" "}
      <span className={`hint ${c.probabilityBand === "high" ? "tips-confirmed" : ""}`}>
        {c.confirmed
          ? `✅ confirmed by ${c.sources.length} models (${c.probabilityBand} confidence)`
          : `(${c.probabilityBand} confidence, ${modelLabel(c.sources[0])} only)`}
      </span>
      {c.factCheckWarnings?.length > 0 &&
        c.factCheckWarnings.map((w, wi) => (
          <p key={wi} className="rec-warning">
            ⚠️ {w}
          </p>
        ))}
    </li>
  );
}

// A companion/pest list, filtered to medium+high confidence by default --
// low-confidence (single-source, weakly self-reported) entries are real
// data, not fabricated, so they're one click away behind a toggle rather
// than gone; just not mixed in undifferentiated with the stronger claims.
function FilteredEntryList({ title, items }) {
  const [showAll, setShowAll] = useState(false);
  const { shown, hidden } = splitByBand(items);
  if (shown.length === 0 && hidden.length === 0) return null;
  return (
    <>
      <strong>{title}</strong>
      <ul className="plan-component-list">
        {(showAll ? items : shown).map((c, i) => (
          <ListEntryRow key={i} c={c} />
        ))}
      </ul>
      {!showAll && hidden.length > 0 && (
        <button type="button" className="chip chip-sm" onClick={() => setShowAll(true)}>
          Show {hidden.length} more (lower-confidence, single-source)
        </button>
      )}
    </>
  );
}

function SourceBlock({ s }) {
  return (
    <div className="tips-source-block">
      <span className="hint tips-source-label">
        {modelLabel(s.model)} says ({s.probabilityBand} confidence):
      </span>
      <p className="hint">{s.text}</p>
      {s.factCheckWarnings?.length > 0 &&
        s.factCheckWarnings.map((w, wi) => (
          <p key={wi} className="rec-warning">
            ⚠️ {w}
          </p>
        ))}
    </div>
  );
}

// Freeform (soil amendment / rotation) sources, same medium+high default
// with the weaker paragraphs behind a toggle -- dropping a whole source's
// paragraph loses more context than dropping one list entry, so this stays
// one click away rather than fully hidden, same principle as the list view.
function FilteredSourceBlocks({ title, sources }) {
  const [showAll, setShowAll] = useState(false);
  if (!sources?.length) return null;
  const { shown, hidden } = splitByBand(sources);
  return (
    <>
      <strong>{title}</strong>
      {(showAll ? sources : shown).map((s, i) => (
        <SourceBlock key={i} s={s} />
      ))}
      {!showAll && hidden.length > 0 && (
        <button type="button" className="chip chip-sm" onClick={() => setShowAll(true)}>
          Show {hidden.length} more (lower-confidence)
        </button>
      )}
    </>
  );
}

// AI-suggested growing tips (companion planting, soil amendment, pest
// management, rotation) -- a lower-trust, supplementary layer, distinct
// from the rest of this app's cited/sourced data. Generated by multiple
// local LLMs answering the same well-scoped questions independently, then
// scored: cross-model agreement (a claim named by 2-3 models independently)
// plus fact-check outcome plus self-reported confidence combine into a real
// probability per claim (see lib.mjs's scoreListEntry/scoreFreeformSentence
// -- self-reported confidence alone was already proven unreliable, so it's
// only one weak input, not the final word). That probability is what
// filters this view: medium+high band shown by default, low band one click
// away, nothing fabricated or silently deleted either way. See
// backend/src/services/growingTips.js for the exact data shape. Fetched
// lazily, only once the farmer actually opens it. Shared between
// BuildPlanner's candidate cards and RecommendationPanel's Shuffle layout
// cards.
export default function GrowingTips({ cropId, cropName, zone, season }) {
  const [tips, setTips] = useState(undefined); // undefined = not fetched yet, null = fetched but no data
  const [loading, setLoading] = useState(false);

  function handleToggle(e) {
    if (!e.target.open || tips !== undefined) return;
    setLoading(true);
    fetch(`${API_BASE}/api/growing-tips?cropId=${cropId}&zone=${zone}&season=${season}`)
      .then((res) => res.json())
      .then((data) => setTips(data.tips))
      .catch(() => setTips(null))
      .finally(() => setLoading(false));
  }

  return (
    <details className="rec-details growing-tips" onToggle={handleToggle}>
      <summary>🌱 AI growing tips{cropName ? ` — ${cropName}` : ""} (unverified)</summary>
      {loading && <p className="hint">Loading…</p>}
      {tips === null && <p className="hint">No AI-suggested tips available for this crop/zone/season yet.</p>}
      {tips && (
        <div className="growing-tips-body">
          <p className="hint disclaimer">
            Generated by multiple AI models answering independently, cross-checked against each other and against
            what this app already knows for certain. Sorted and filtered by a computed confidence score — see the
            lower-confidence toggle for what's held back by default. Treat as a starting point to verify locally, not
            fact.
          </p>
          <FilteredEntryList title="Companion planting" items={tips.companionPlanting ?? []} />
          <FilteredEntryList title="Pest & disease management" items={tips.pestDisease ?? []} />
          <FilteredSourceBlocks title="Soil amendment" sources={tips.soilAmendment?.bySource} />
          <FilteredSourceBlocks title="Multi-year rotation" sources={tips.rotationSequence?.bySource} />
        </div>
      )}
    </details>
  );
}
